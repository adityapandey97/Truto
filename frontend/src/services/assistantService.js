import { mockConversations, deterministicPromptResponses } from '../data/conversations.js';
import { simulateDelay, getStorageData, setStorageData } from './mockApi.js';
import { IS_DEMO_MODE, apiClient } from './api.js';

const STORAGE_KEY = 'conversations';

function getLocalConversations() {
  return getStorageData(STORAGE_KEY, mockConversations);
}

export const assistantService = {
  async getConversations() {
    if (!IS_DEMO_MODE) {
      const response = await apiClient.get('/conversations');
      return response.data;
    }
    await simulateDelay(250);
    return getLocalConversations();
  },

  async getConversationById(id) {
    if (!IS_DEMO_MODE) {
      const response = await apiClient.get(`/conversations/${id}`);
      return response.data;
    }
    await simulateDelay(200);
    const convs = getLocalConversations();
    const conv = convs.find((c) => c.id === id);
    if (!conv) throw new Error(`Conversation not found: ${id}`);
    return conv;
  },

  async createConversation(repositoryId = 'repo-codepilot-core', title = 'New Conversation') {
    if (!IS_DEMO_MODE) {
      const response = await apiClient.post('/conversations', { repositoryId, title });
      return response.data;
    }
    await simulateDelay(300);
    const convs = getLocalConversations();
    const newConv = {
      id: `conv-${Date.now()}`,
      title,
      repositoryId,
      createdAt: new Date().toISOString(),
      updatedAt: new Date().toISOString(),
      messages: []
    };
    const updated = [newConv, ...convs];
    setStorageData(STORAGE_KEY, updated);
    return newConv;
  },

  async renameConversation(id, newTitle) {
    if (!IS_DEMO_MODE) {
      const response = await apiClient.patch(`/conversations/${id}`, { title: newTitle });
      return response.data;
    }
    await simulateDelay(200);
    const convs = getLocalConversations();
    const conv = convs.find((c) => c.id === id);
    if (!conv) throw new Error(`Conversation not found: ${id}`);
    conv.title = newTitle;
    conv.updatedAt = new Date().toISOString();
    setStorageData(STORAGE_KEY, convs);
    return conv;
  },

  async deleteConversation(id) {
    if (!IS_DEMO_MODE) {
      await apiClient.delete(`/conversations/${id}`);
      return true;
    }
    await simulateDelay(200);
    const convs = getLocalConversations();
    const filtered = convs.filter((c) => c.id !== id);
    setStorageData(STORAGE_KEY, filtered);
    return true;
  },

  async sendMessage(conversationId, content) {
    if (!IS_DEMO_MODE) {
      const response = await apiClient.post(`/conversations/${conversationId}/messages`, { content });
      return response.data;
    }

    // Realistic typing delay for assistant simulation
    await simulateDelay(600);

    const convs = getLocalConversations();
    const conv = convs.find((c) => c.id === conversationId);
    if (!conv) throw new Error(`Conversation not found: ${conversationId}`);

    const userMessage = {
      id: `msg-${Date.now()}-u`,
      role: 'user',
      content,
      fileReferences: [],
      createdAt: new Date().toISOString()
    };

    // Determine mock response
    let assistantReply = deterministicPromptResponses[content.trim()];
    if (!assistantReply) {
      assistantReply = `### Simulated Response (Demo Mode)

Analyzing query: **"${content}"** against codebase index.

\`\`\`javascript
// Simulated contextual snippet for: ${content.slice(0, 30)}...
function handleContextQuery(query) {
  return { status: "simulated", context: "Demo repository analysis" };
}
\`\`\`

> **Frontend Demo Notice**: This response was generated by CodePilot's mock assistant service. Full LLM semantic retrieval and RAG pipeline integration will occur in Phase 4.`;
    }

    const assistantMessage = {
      id: `msg-${Date.now()}-a`,
      role: 'assistant',
      content: assistantReply,
      fileReferences: ['src/index.js'],
      createdAt: new Date().toISOString()
    };

    conv.messages.push(userMessage, assistantMessage);
    conv.updatedAt = new Date().toISOString();
    setStorageData(STORAGE_KEY, convs);

    return { userMessage, assistantMessage };
  }
};
